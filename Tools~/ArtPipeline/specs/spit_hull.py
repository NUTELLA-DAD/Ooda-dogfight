def extras(C):
    loft, tube, part, wing_low, BODY, np = C['loft'], C['tube'], C['part'], C['wing_low'], C['BODY'], C['np']
    b = C['bodies'][0]
    # the two radiators under the wings, a little in from the gear (the Mk IX's are alike)
    for sgn in (1, -1):
        xc = 1.45; secs = []
        for (y, d, wf) in ((-1.95, 0.03, 0.75), (-1.85, 0.11, 0.95), (-1.55, 0.14, 1.0), (-1.20, 0.13, 1.0), (-1.00, 0.09, 0.92), (-0.88, 0.04, 0.8)):
            zl = wing_low(xc, y); secs.append((y, 0.24 * wf, zl + 0.05, zl - d))
        loft(BODY, 'rad' + ('L' if sgn > 0 else 'R'), secs, mouth=0.05, x=sgn * xc)
    # the carburettor intake under the nose
    loft(BODY, 'chin', [(-3.05, 0.10, -0.60, -0.78), (-2.95, 0.13, -0.62, -0.86), (-2.60, 0.14, -0.66, -0.90), (-2.25, 0.12, -0.74, -0.92), (-2.05, 0.06, -0.82, -0.93)], mouth=0.04)
    # six exhaust stubs each side, along the cowl
    for sgn in (-1, 1):
        for k in range(6):
            y = -3.55 + k * 0.17; z = 0.22
            hx = b.half_x(y, z)
            tube((sgn * (hx - 0.04), y, z), (sgn * (hx + 0.07), y + 0.08, z - 0.03), 0.050, 0.044, 'sw_steel', nseg=8, squash=0.7)
    # the 20 mm cannon out of the leading edge, the mast and the pitot
    le = C['WING'][0]; mid = C['WING'][2]
    for sgn in (-1, 1):
        s = 1.95; tube((sgn * s, le(s) + 0.25, mid(s) - 0.02), (sgn * s, le(s) - 0.42, mid(s) - 0.02), 0.045, 0.034, 'sw_steel', nseg=10)
    tube((0, 0.30, b.top(0, 0.30) - 0.03), (0, 0.38, b.top(0, 0.30) + 0.62), 0.032, 0.014, 'sw_paint', nseg=8, squash=0.45)
    s = 4.6; tube((-s, le(s) + 0.30, mid(s) - 0.10), (-s, le(s) - 0.18, mid(s) - 0.10), 0.014, 0.010, 'sw_steel', nseg=6)
